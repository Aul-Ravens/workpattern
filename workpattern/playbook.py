def messages(feedback: str) -> list[dict[str, str]]:
    return [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content": feedback},
    ]


def workflow(code: str) -> dict:
    route = ROUTES[code]
    return {
        "code": code,
        "title": route.title,
        "criterion": route.criterion,
        "steps": [{"title": title, "detail": detail} for title, detail in route.steps],
    }
